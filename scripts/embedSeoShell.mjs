/**
 * Post-build: embeds dist/index.html into src/lib/seo/seoShell.generated.js so the SEO
 * middleware has the SPA shell without fetching "/" from itself on every request.
 *
 * Vercel runs the build command before bundling middleware.js, so the bundle picks up
 * this file. Runs only on Vercel (or with EMBED_SEO_SHELL=1) so local builds don't
 * leave the committed placeholder modified.
 */

import { existsSync, readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const shellPath = join(root, "dist/index.html");
const outPath = join(root, "src/lib/seo/seoShell.generated.js");

if (!process.env.VERCEL && process.env.EMBED_SEO_SHELL !== "1") {
  console.log("[embedSeoShell] skipped (not a Vercel build; set EMBED_SEO_SHELL=1 to force)");
  process.exit(0);
}

if (!existsSync(shellPath)) {
  console.error("[embedSeoShell] dist/index.html missing — run after vite build + prerender");
  process.exit(1);
}

const html = readFileSync(shellPath, "utf8");
if (!html.includes("</head>") || !html.includes("</body>")) {
  console.error("[embedSeoShell] dist/index.html does not look like the SPA shell");
  process.exit(1);
}

writeFileSync(
  outPath,
  `// Generated by scripts/embedSeoShell.mjs from dist/index.html. Do not commit.\n` +
    `export const SEO_SHELL_HTML = ${JSON.stringify(html)};\n`
);
console.log(`[embedSeoShell] embedded ${html.length} bytes into src/lib/seo/seoShell.generated.js`);
