function makePreviewPayload(base, overrides = {}) {
  return {
    ...base,
    ...overrides,
    menu_presentation: {
      ...(base.menu_presentation || {}),
      ...(overrides.menu_presentation || {}),
    },
    sections: overrides.sections || base.sections || [],
    deal_items: overrides.deal_items || base.deal_items || [],
  };
}

