export function formatLabel(template, values = {}) {
  return String(template || "").replace(/\{(\w+)\}/g, (_, key) => {
    const value = values[key];
    return value === undefined || value === null ? "" : String(value);
  });
}

export function getLabelValue(language, key, fallback = "", values) {
  const normalized = String(language || "en").trim().toLowerCase();
  const dict = UI_LABELS[normalized] || UI_LABELS.en;
  const raw = dict[key] || UI_LABELS.en[key] || fallback || key;
  return values ? formatLabel(raw, values) : raw;
}
